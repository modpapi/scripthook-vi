// Generates sdk/include/shvi/natives_vi.hpp from a VI native table (TASKS T2.10).
//
//   node tools/docgen/gen_natives.js crossmap/gta6_xbox_1.0.2.1.json sdk/include/shvi/natives_vi.hpp
//   node tools/docgen/gen_natives.js <table.json> <header> --check   exit 1 if the header is stale
//
// One inline wrapper per native, in namespace shvi::natives::<NAMESPACE>,
// calling the name through the SDK's hash API (sdk::EngineHash), like
// ScriptHookV's natives.h. Entries with "deny": true are left out. A table
// entry needs "params" (argument types) to get a typed wrapper; without it
// the wrapper is skipped and listed at the end of the header.
//
// Types (VM cells are 8 bytes):
//   int -> std::int32_t   uint -> std::uint32_t (hashes)   float   bool
//   entity  -> shvi_entity_ref, 2 cells (16-byte script reference)
//   vector3 -> shvi::natives::Vec3, 2 cells: x and y packed in the first, z in the second
//   string  -> std::uint64_t, a System.String reference (scripts own those; pass one you got back)
'use strict';
const fs = require('fs');

const [, , tablePath, outPath, flag] = process.argv;
if (!tablePath || !outPath) {
  console.error('usage: gen_natives.js <table.json> <out.hpp> [--check]');
  process.exit(2);
}
const table = JSON.parse(fs.readFileSync(tablePath, 'utf8'));

const ARG = {
  int: { type: 'std::int32_t', push: (n) => `p(a, to_slot(${n}));` },
  uint: { type: 'std::uint32_t', push: (n) => `p(a, to_slot(${n}));` },
  float: { type: 'float', push: (n) => `p(a, to_slot(${n}));` },
  bool: { type: 'bool', push: (n) => `p(a, to_slot(${n}));` },
  string: { type: 'std::uint64_t', push: (n) => `p(a, ${n});` },
  entity: { type: 'shvi_entity_ref', push: (n) => `p(a, ${n}.lo); p(a, ${n}.hi);` },
  vector3: { type: 'Vec3', push: (n) => `p(a, pack_xy(${n})); p(a, to_slot(${n}.z));` },
};
const RET = {
  int: 'std::int32_t', uint: 'std::uint32_t', float: 'float', bool: 'bool',
  entity: 'shvi_entity_ref', vector3: 'Vec3', string: 'std::uint64_t',
};

const byNs = new Map();
const skipped = [];
for (const [name, e] of Object.entries(table.natives)) {
  if (e.deny) continue;
  const params = e.params;
  const ret = e.ret == null ? null : e.ret;
  if (!Array.isArray(params) || params.some((t) => !ARG[t]) || (ret !== null && !RET[ret])) {
    skipped.push(name);
    continue;
  }
  const cells = params.reduce((n, t) => n + (t === 'entity' || t === 'vector3' ? 2 : 1), 0);
  if (typeof e.args === 'number' && e.args !== cells) {
    console.error(`${name}: params take ${cells} cells, table says args ${e.args}`);
    process.exit(1);
  }
  const ns = (e.namespace || 'MISC').replace(/[^A-Z0-9_]/gi, '_');
  if (!byNs.has(ns)) byNs.set(ns, []);
  byNs.get(ns).push({ name, params, ret, e });
}

const L = [];
L.push('// GENERATED by tools/docgen/gen_natives.js from ' + tablePath.replace(/\\/g, '/') + '. Do not edit.');
L.push('// GTA VI natives by name, for plugins (ScriptHookV natives.h style). Build ' +
       `${table.build.exe || ''} ${table.build.version || ''} (PE timestamp ${table.build.pe_timestamp}).`);
L.push('// A wrapper calls the name through the host; the host binds it only if its');
L.push('// native table names the running build and the handler id matches, else the');
L.push('// call returns zeros. Static analysis only: nothing here has run in a game.');
L.push('#pragma once');
L.push('#include "shvi.hpp"');
L.push('');
L.push('#include <cstdint>');
L.push('#include <cstring>');
L.push('');
L.push('namespace shvi::natives {');
L.push('');
L.push('// A script Vector3 as natives take and return it: x, y, z (+ padding) in two cells.');
L.push('struct Vec3 { float x, y, z, w; };');
L.push('static_assert(sizeof(Vec3) == 16);');
L.push('');
L.push('namespace detail {');
L.push('inline void p(const shvi_api* a, std::uint64_t v) { a->native_push64(v); }');
L.push('inline std::uint64_t pack_xy(const Vec3& v) { return to_slot(v.x) | (to_slot(v.y) << 32); }');
L.push('template <class R> inline R ret(const std::uint64_t* r) {');
L.push('    if constexpr (std::is_same_v<R, bool>) return (r[0] & 0xFF) != 0;');
L.push('    else { R out; std::memcpy(&out, r, sizeof(R)); return out; }');
L.push('}');
L.push('}  // namespace detail');
for (const [ns, list] of [...byNs.entries()].sort((x, y) => x[0].localeCompare(y[0]))) {
  L.push('');
  L.push(`namespace ${ns} {`);
  for (const { name, params, ret, e } of list.sort((x, y) => x.name.localeCompare(y.name))) {
    const args = params.map((t, i) => `${ARG[t].type} a${i}`).join(', ');
    const rt = ret === null ? 'void' : RET[ret];
    L.push(`// ${e.confidence || '?'}: ${String(e.evidence || '').replace(/\s+/g, ' ').slice(0, 160)}`);
    L.push(`inline ${rt} ${name}(${args}) {`);
    L.push('    using namespace detail;');
    L.push('    const shvi_api* a = ::shvi::api();');
    L.push(`    a->native_init(::shvi::sdk::EngineHash("${name}"));`);
    params.forEach((t, i) => L.push('    ' + ARG[t].push(`a${i}`)));
    if (ret === null) L.push('    a->native_call();');
    else L.push(`    return ret<${rt}>(a->native_call());`);
    L.push('}');
  }
  L.push(`}  // namespace ${ns}`);
}
L.push('');
L.push('}  // namespace shvi::natives');
if (skipped.length) L.push('// Not generated (no params in the table): ' + skipped.join(', '));
L.push('');
const text = L.join('\n');

if (flag === '--check') {
  const cur = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== text) {
    console.error(`${outPath} is stale: run node tools/docgen/gen_natives.js ${tablePath} ${outPath}`);
    process.exit(1);
  }
  console.log(`${outPath} is current (${[...byNs.values()].reduce((n, l) => n + l.length, 0)} wrappers)`);
} else {
  fs.writeFileSync(outPath, text);
  console.log(`wrote ${outPath}: ${[...byNs.values()].reduce((n, l) => n + l.length, 0)} wrappers, ${skipped.length} skipped`);
}
